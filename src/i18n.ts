let chineseRegions: Map<string, string | undefined> | undefined;
export function countryLabel(name: string, language: Language) {
  if (language === 'en') return name;
  if (name === 'Nomadic') return '无固定居住地';
  if (!chineseRegions) {
    const english = new Intl.DisplayNames('en', { type: 'region', fallback: 'none' });
    const localized = new Intl.DisplayNames('zh-CN', { type: 'region', fallback: 'none', style: 'short' });
    chineseRegions = new Map();
    for (const first of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') {
      for (const second of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') {
        const code = first + second;
        const label = english.of(code);
        if (label) chineseRegions.set(label, localized.of(code));
      }
    }
    for (const [label, code] of Object.entries(regionCodes)) chineseRegions.set(label, localized.of(code));
  }
  return chineseRegions.get(name) ?? name;
}

const interpolate: Translate = (message, values) => {
  return values ? message.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : message;
};

export const translations: Record<Language, Translate> = {
  en: interpolate,
  'zh-CN': (message, values) => interpolate((Object.hasOwn(chinese, message) ? chinese[message] : undefined) ?? message, values),
};
